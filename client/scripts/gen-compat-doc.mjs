// Generates docs/compatibility.md from src/utilities/versionRequirements.json,
// the table the extension uses to check the language server version.
// Fails if the current extension version has no entry, or if an entry
// requires a server newer than the extension itself. The second check keeps
// the doc's "same version" advice true.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const clientDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const requirementsPath = join(
    clientDir,
    "src/utilities/versionRequirements.json",
);
const outputPath = join(clientDir, "../docs/compatibility.md");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const requirements = readJson(requirementsPath);
const { version } = readJson(join(clientDir, "package.json"));

// Compares plain x.y.z versions, which is all the table holds.
const compare = (a, b) => {
    const [pa, pb] = [a, b].map((v) => v.split(".").map(Number));
    for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
        const d = (pa[i] ?? 0) - (pb[i] ?? 0);
        if (d !== 0) return d;
    }
    return 0;
};

const errors = [];
if (!(version in requirements)) {
    errors.push(
        `version ${version} from package.json has no entry in versionRequirements.json`,
    );
}
for (const [extension, server] of Object.entries(requirements)) {
    if (compare(server, extension) > 0) {
        errors.push(
            `extension ${extension} requires server ${server}, which is newer than the extension`,
        );
    }
}
if (errors.length > 0) {
    for (const e of errors) console.error(`gen-compat-doc: ${e}`);
    process.exit(1);
}

const rows = Object.entries(requirements)
    .sort(([a], [b]) => compare(b, a))
    .map(([extension, server]) => `| ${extension} | ${server} |`);

const doc = `<!-- Generated by client/scripts/gen-compat-doc.mjs from client/src/utilities/versionRequirements.json.
     Do not edit by hand. Change the JSON file and run \`npm run gen-compat-doc\` in client/. -->

# Extension and language server compatibility

The VsRocq extension and the opam package \`vsrocq-language-server\` are installed
and updated separately. Each extension version requires a minimum language server
version, listed in the table below. If your language server is older, the extension
shows an error saying "This version of VsRocq requires version X of
vsrocq-language-server".

Installing the same version of both always meets the requirement. To find the newest
extension version your language server meets the requirement for, take the first row
from the top whose minimum is at or below your language server version.

To check which versions you have, run **Rocq: Troubleshooting: Show setup** from the
command palette (F1).

| Extension version | Minimum \`vsrocq-language-server\` version |
|---|---|
${rows.join("\n")}
`;

writeFileSync(outputPath, doc);
